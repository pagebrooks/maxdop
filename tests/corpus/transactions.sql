COMMIT;
GO

BEGIN TRANSACTION OrderUpdate;
UPDATE dbo.Orders SET Total = 1.00 WHERE OrderId = 1;
COMMIT TRANSACTION OrderUpdate;
GO

BEGIN TRANSACTION WITH MARK N'Nightly load';
COMMIT TRANSACTION;
GO

BEGIN TRANSACTION;
SAVE TRANSACTION BeforeInsert;
INSERT INTO dbo.Orders (OrderId, CustomerId, Total, OrderDate) VALUES (2, 1, 5.00, '2026-01-02');
ROLLBACK TRANSACTION BeforeInsert;
COMMIT TRANSACTION;
GO

BEGIN TRANSACTION;
IF @@TRANCOUNT > 0
    ROLLBACK TRANSACTION;
GO

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;
SET TRANSACTION ISOLATION LEVEL READ COMMITTED;
SET TRANSACTION ISOLATION LEVEL REPEATABLE READ;
SET TRANSACTION ISOLATION LEVEL SNAPSHOT;
SET TRANSACTION ISOLATION LEVEL SERIALIZABLE;
GO

